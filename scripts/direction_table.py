"""Classify every recorded trajectory by the direction of its edit against the case's reference path.

Offline analysis of an existing results directory: reads runs.jsonl and the case definitions,
calls no model. Each of the four match modes in evals/checks/trajectory.py is a pure function of
this direction set (strict: empty; unordered: empty or reordering; subset: no insertion;
superset: no omission), so a fault and a valid path with the same set get the same verdict
from every mode.

    uv run python -m scripts.direction_table --runs results/part-1
"""
from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

from evals.schema import load_cases


def edit_directions(observed: list[str], reference: list[str]) -> tuple[str, ...]:
    obs, ref = Counter(observed), Counter(reference)
    directions = set()
    if ref - obs:
        directions.add("omission")
    if obs - ref:
        directions.add("insertion")
    if not directions and observed != reference:
        directions.add("reordering")
    return tuple(sorted(directions))


def table(runs: list[dict], cases: dict) -> dict[str, Counter]:
    out: dict[str, Counter] = {}
    for r in runs:
        calls = [c["name"] for c in r["tool_calls"]]
        key = edit_directions(calls, cases[r["case_id"]].reference_trajectory)
        out.setdefault(r["variant"], Counter())[key] += 1
    return out


def render(result: dict[str, Counter]) -> str:
    lines = ["| Variant | Direction set | Runs |", "|---|---|---|"]
    for variant, counts in result.items():
        for key, n in counts.most_common():
            lines.append(f"| {variant} | {key if key else '()'} | {n} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", default="results/part-1")
    parser.add_argument("--cases", default="evals/cases")
    args = parser.parse_args(argv)
    runs_dir = Path(args.runs)
    cases = {c.id: c for c in load_cases(Path(args.cases))}
    runs = [json.loads(line) for line in (runs_dir / "runs.jsonl").read_text(encoding="utf-8").splitlines()]
    md = "# Edit-direction table\n\nGenerated by `scripts/direction_table.py` from `runs.jsonl`.\n\n" + render(table(runs, cases))
    (runs_dir / "direction-table.md").write_text(md, encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
