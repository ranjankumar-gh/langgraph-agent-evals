"""Re-grade recorded runs with a position rule added to the per-case trajectory constraints.

Offline analysis of an existing results directory: reads runs.jsonl, calls no model. Two rules:

- lookup_only: a repeat lookup_order is allowed only as the call directly before issue_refund.
  Written after watching mutant C survive the uniform max_calls cap, so it is fitted to C.
- any_read:    a repeat of ANY read tool (lookup_order, get_refund_history) is allowed only as
  the call directly before issue_refund.
- any_read_or_stop: as any_read, but a repeat read may also be the run's last tool call - the
  shape of a verifying re-read that found a change and stopped (alt_verify on changed_order).
  Also written after seeing results, so also fitted.

Reported per rule: mutant survival (three-artifact harness plus the rule, counted on fired pairs
whose baseline passes the same harness) and the brittle-fail rate of valid variants (runs whose
end state and answer pass, rejected by constraints plus the rule).

    uv run python -m scripts.regrade_position_rule --runs results/part-1
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from agent.graph import MUTANTS, VALID_VARIANTS

READ_TOOLS = ("lookup_order", "get_refund_history")


def repeats_only_before_refund(calls: list[str], tools: tuple[str, ...], allow_last: bool = False) -> bool:
    seen: set[str] = set()
    for i, call in enumerate(calls):
        if call not in tools:
            continue
        if call not in seen:
            seen.add(call)
            continue
        if i + 1 >= len(calls):
            if not allow_last:
                return False
        elif calls[i + 1] != "issue_refund":
            return False
    return True


RULES = {
    "none": None,
    "lookup_only": ("lookup_order",),
    "any_read": READ_TOOLS,
    "any_read_or_stop": READ_TOOLS,
}


def names(run: dict) -> list[str]:
    return [c["name"] for c in run["tool_calls"]]


def rule_ok(run: dict, rule: str) -> bool:
    tools = RULES[rule]
    if tools is None:
        return True
    return repeats_only_before_refund(names(run), tools, allow_last=(rule == "any_read_or_stop"))


def passes(run: dict, rule: str) -> bool:
    return (not run["crashed"] and run["answer_pass"] and run["end_state_pass"]
            and run["constraints_pass"] and rule_ok(run, rule))


def regrade(runs: list[dict]) -> dict[str, dict[str, str]]:
    base = {(r["case_id"], r["trial"]): r for r in runs if r["variant"] == "baseline"}
    present = {r["variant"] for r in runs}
    out: dict[str, dict[str, str]] = {}
    for rule in RULES:
        row: dict[str, str] = {}
        for m in (v for v in MUTANTS if v in present):
            k = n = 0
            for r in runs:
                if r["variant"] != m or not any(f.startswith(m + ":") for f in r["mutations_fired"]):
                    continue
                b = base.get((r["case_id"], r["trial"]))
                if b is None or not passes(b, rule):
                    continue
                n += 1
                k += passes(r, rule)
            row[f"{m} survives"] = f"{k}/{n}"
        for v in (v for v in VALID_VARIANTS if v in present and v != "baseline"):
            k = n = 0
            for r in runs:
                if r["variant"] != v or r["crashed"] or not (r["answer_pass"] and r["end_state_pass"]):
                    continue
                n += 1
                k += not (r["constraints_pass"] and rule_ok(r, rule))
            row[f"{v} rejected"] = f"{k}/{n}"
        out[rule] = row
    return out


def render(result: dict[str, dict[str, str]]) -> str:
    cols = list(next(iter(result.values())))
    lines = ["| Rule | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    for rule, row in result.items():
        lines.append(f"| {rule} | " + " | ".join(row[c] for c in cols) + " |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", default="results/part-1")
    args = parser.parse_args(argv)
    runs_dir = Path(args.runs)
    runs = [json.loads(line) for line in (runs_dir / "runs.jsonl").read_text(encoding="utf-8").splitlines()]
    md = ("# Position-rule re-grade\n\nGenerated by `scripts/regrade_position_rule.py` from `runs.jsonl`. "
          "`none` reproduces the three-artifact harness as measured.\n\n" + render(regrade(runs)))
    (runs_dir / "position-rule-regrade.md").write_text(md, encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
