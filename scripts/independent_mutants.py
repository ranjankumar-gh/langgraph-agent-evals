"""Score the independently authored mutants M1-M8 (docs/part-1.2-preregistration.md).

Offline analysis of a results directory: reads runs.jsonl and the case definitions, calls no
model. For each mutant, counted on fired (case, trial) pairs whose baseline passes the same
harness:

- survival under answer-only, under each match mode (end state + answer + mode), under the
  three-artifact harness with per-case constraints, and under each position rule;
- the edit-direction sets of its fired runs, and which valid variants share them;
- whether every mode verdict equals the verdict the direction set predicts.

M7 is reported but excluded from the aggregate, as pre-registered.

    uv run python -m scripts.independent_mutants --runs results/part-1.2
"""
from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path

from agent.graph import INDEPENDENT_MUTANTS, VALID_VARIANTS
from evals.schema import load_cases
from scripts.direction_table import edit_directions
from scripts.regrade_position_rule import RULES, rule_ok

MODES = ("strict", "unordered", "subset", "superset")
EXCLUDED = ("M7",)


def predicted(mode: str, dirs: tuple[str, ...]) -> bool:
    s = set(dirs)
    return {
        "strict": not s,
        "unordered": s <= {"reordering"},
        "subset": "insertion" not in s,
        "superset": "omission" not in s,
    }[mode]


def harnesses() -> dict[str, callable]:
    def ok(r):
        return not r["crashed"] and not r["grading_error"]
    h = {"answer only": lambda r: ok(r) and r["answer_pass"]}
    for m in MODES:
        h[f"mode {m}"] = lambda r, m=m: ok(r) and r["answer_pass"] and r["end_state_pass"] and r["mode_pass"][m]
    for rule in RULES:
        label = "three layers, constraints" if rule == "none" else f"three layers + {rule}"
        h[label] = lambda r, rule=rule: (ok(r) and r["answer_pass"] and r["end_state_pass"]
                                          and r["constraints_pass"] and rule_ok(r, rule))
    return h


def fired(r: dict) -> bool:
    return any(f.startswith(r["variant"] + ":") for f in r["mutations_fired"])


def analyse(runs: list[dict], refs: dict[str, list[str]]) -> dict:
    base = {(r["case_id"], r["trial"]): r for r in runs if r["variant"] == "baseline"}
    present = [m for m in INDEPENDENT_MUTANTS if any(r["variant"] == m for r in runs)]
    hs = harnesses()
    survival: dict[str, dict[str, str]] = {}
    totals = Counter()
    for name, h in hs.items():
        row = {}
        for m in present:
            k = n = 0
            for r in runs:
                if r["variant"] != m or not fired(r):
                    continue
                b = base.get((r["case_id"], r["trial"]))
                if b is None or not h(b):
                    continue
                n += 1
                k += h(r)
            row[m] = f"{k}/{n}"
            if m not in EXCLUDED:
                totals[(name, "k")] += k
                totals[(name, "n")] += n
        row["all counted"] = f"{totals[(name, 'k')]}/{totals[(name, 'n')]}"
        survival[name] = row

    def dirs(r):
        return edit_directions([c["name"] for c in r["tool_calls"]], refs[r["case_id"]])

    by_dir: dict[str, Counter] = defaultdict(Counter)
    mismatches = []
    for r in runs:
        if r["crashed"]:
            continue
        v = r["variant"]
        if v in INDEPENDENT_MUTANTS and not fired(r):
            continue
        d = dirs(r)
        by_dir[v][d] += 1
        for m in MODES:
            if r["mode_pass"][m] != predicted(m, d):
                mismatches.append((r["case_id"], v, r["trial"], m))
    valid_sets = {d for v in VALID_VARIANTS for d in by_dir.get(v, {})}
    collisions = {m: sorted(" ".join(d) or "()" for d in by_dir.get(m, {}) if d in valid_sets) for m in present}
    return {"survival": survival, "by_dir": by_dir, "mismatches": mismatches, "collisions": collisions,
            "present": present}


def render(res: dict) -> str:
    cols = res["present"] + ["all counted"]
    out = ["# Independently authored mutants M1-M8", "",
           "Generated by `scripts/independent_mutants.py`. Survival is counted on fired (case, trial) pairs",
           "whose baseline passes the same harness. M7 is excluded from `all counted` (pre-registered:",
           "harmless in this environment).", "",
           "## Survival by harness", "",
           "| Harness | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    for name, row in res["survival"].items():
        out.append(f"| {name} | " + " | ".join(row[c] for c in cols) + " |")
    out += ["", "## Edit-direction sets (fired runs only for mutants)", "",
            "| Variant | Direction sets |", "|---|---|"]
    for v, c in res["by_dir"].items():
        cells = ", ".join(f"`{' '.join(d) or '()'}` {n}" for d, n in sorted(c.items(), key=lambda x: -x[1]))
        out.append(f"| {v} | {cells} |")
    out += ["", "## Direction sets each mutant shares with a valid variant", ""]
    for m, sets in res["collisions"].items():
        out.append(f"- {m}: " + (", ".join(f"`{s}`" for s in sets) if sets else "none"))
    out += ["", f"## Mode verdicts that disagree with the direction-set prediction: {len(res['mismatches'])}", ""]
    out += [f"- {c} {v} t{t} {m}" for c, v, t, m in res["mismatches"][:50]]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", default="results/part-1.2")
    parser.add_argument("--cases", default="evals/cases")
    args = parser.parse_args(argv)
    runs_dir = Path(args.runs)
    runs = [json.loads(line) for line in (runs_dir / "runs.jsonl").read_text(encoding="utf-8").splitlines()]
    refs = {c.id: c.reference_trajectory for c in load_cases(Path(args.cases))}
    md = render(analyse(runs, refs))
    (runs_dir / "independent-mutants.md").write_text(md, encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
