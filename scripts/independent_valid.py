"""Score the independently authored valid alternates V1-V6 (docs/part-1.3-preregistration.md).

Offline analysis of a results directory: reads runs.jsonl and the case definitions, calls no
model. For each alternate, among non-crashed runs whose end state and answer pass:

- how many each trajectory check rejects (brittle-fail), overall and on fired runs;
- the edit-direction sets of its fired runs;
- whether every mode verdict equals the verdict the direction set predicts;
- for V4-V6, whether every run's tool calls equal the baseline's on the same (case, trial).

    uv run python -m scripts.independent_valid --runs results/part-1.3
"""
from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path

from agent.graph import INDEPENDENT_VALID
from evals.schema import load_cases
from scripts.direction_table import edit_directions
from scripts.independent_mutants import MODES, predicted
from scripts.regrade_position_rule import RULES, rule_ok

CONTROLS = ("V4", "V5", "V6")


def checks() -> dict[str, callable]:
    c = {f"mode {m}": (lambda r, m=m: r["mode_pass"][m]) for m in MODES}
    for rule in RULES:
        label = "constraints" if rule == "none" else f"constraints + {rule}"
        c[label] = lambda r, rule=rule: r["constraints_pass"] and rule_ok(r, rule)
    return c


def names(r: dict) -> list[str]:
    return [c["name"] for c in r["tool_calls"]]


def fired(r: dict) -> bool:
    return any(f.startswith(r["variant"] + ":") for f in r["mutations_fired"])


def analyse(runs: list[dict], refs: dict[str, list[str]]) -> dict:
    ok = [r for r in runs if not r["crashed"] and not r["grading_error"]]
    base = {(r["case_id"], r["trial"]): r for r in ok if r["variant"] == "baseline"}
    present = [v for v in INDEPENDENT_VALID if any(r["variant"] == v for r in ok)]
    cs = checks()
    table: dict[str, dict[str, str]] = {}
    for name, check in cs.items():
        row = {}
        for v in ["baseline"] + present:
            good = [r for r in ok if r["variant"] == v and r["answer_pass"] and r["end_state_pass"]]
            f = [r for r in good if fired(r)]
            rej = sum(not check(r) for r in good)
            frej = sum(not check(r) for r in f)
            row[v] = f"{rej}/{len(good)}" + (f" (fired {frej}/{len(f)})" if v not in ("baseline",) + CONTROLS else "")
        table[name] = row

    by_dir: dict[str, Counter] = defaultdict(Counter)
    mismatches, cases_by_v = [], defaultdict(Counter)
    for r in ok:
        v = r["variant"]
        d = edit_directions(names(r), refs[r["case_id"]])
        if v in INDEPENDENT_VALID and fired(r):
            by_dir[v][d] += 1
            cases_by_v[v][r["case_id"]] += 1
        for m in MODES:
            if r["mode_pass"][m] != predicted(m, d):
                mismatches.append((r["case_id"], v, r["trial"], m))

    control_diffs, end_diffs = [], []
    for r in ok:
        b = base.get((r["case_id"], r["trial"]))
        if b is None or r["variant"] not in present:
            continue
        if r["variant"] in CONTROLS and names(r) != names(b):
            control_diffs.append((r["case_id"], r["variant"], r["trial"], names(r), names(b)))
        if r["end_state_pass"] != b["end_state_pass"]:
            end_diffs.append((r["case_id"], r["variant"], r["trial"]))
    return {"table": table, "present": present, "by_dir": by_dir, "cases": cases_by_v,
            "mismatches": mismatches, "control_diffs": control_diffs, "end_diffs": end_diffs}


def render(res: dict) -> str:
    cols = ["baseline"] + res["present"]
    out = ["# Independently authored valid alternates V1-V6", "",
           "Generated by `scripts/independent_valid.py`. Cells: runs rejected / runs whose end state and",
           "answer pass; for V1-V3 also the same count on fired runs only. V4-V6 are controls whose tool",
           "calls should equal the baseline's.", "",
           "## Brittle-fail by check", "",
           "| Check | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    for name, row in res["table"].items():
        out.append(f"| {name} | " + " | ".join(row[c] for c in cols) + " |")
    out += ["", "## Fired runs: cases and edit-direction sets", "", "| Variant | Cases | Direction sets |", "|---|---|---|"]
    for v in res["present"]:
        cases = ", ".join(f"{c} {n}" for c, n in sorted(res["cases"][v].items())) or "none"
        dirs = ", ".join(f"`{' '.join(d) or '()'}` {n}" for d, n in res["by_dir"][v].items()) or "none"
        out.append(f"| {v} | {cases} | {dirs} |")
    out += ["", f"## Mode verdicts that disagree with the direction-set prediction: {len(res['mismatches'])}", ""]
    out += [f"- {c} {v} t{t} {m}" for c, v, t, m in res["mismatches"][:50]]
    out += ["", f"## Control runs (V4-V6) whose tool calls differ from the baseline's: {len(res['control_diffs'])}", ""]
    out += [f"- {c} {v} t{t}: {a} vs {b}" for c, v, t, a, b in res["control_diffs"][:50]]
    out += ["", f"## Runs whose end-state verdict differs from the baseline's on the same (case, trial): "
            f"{len(res['end_diffs'])}", ""]
    out += [f"- {c} {v} t{t}" for c, v, t in res["end_diffs"][:50]]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", default="results/part-1.3")
    parser.add_argument("--cases", default="evals/cases")
    args = parser.parse_args(argv)
    runs_dir = Path(args.runs)
    runs = [json.loads(line) for line in (runs_dir / "runs.jsonl").read_text(encoding="utf-8").splitlines()]
    refs = {c.id: c.reference_trajectory for c in load_cases(Path(args.cases))}
    md = render(analyse(runs, refs))
    (runs_dir / "independent-valid.md").write_text(md, encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
